export default async function handler(req, res) {

    // ==================================================
    // CORS
    // ==================================================

    const origin = req.headers.origin;

    const allowedOrigin =
        process.env.TILDA_ORIGIN || "*";

    if (
        allowedOrigin === "*" ||
        origin === allowedOrigin
    ) {
        res.setHeader(
            "Access-Control-Allow-Origin",
            allowedOrigin === "*"
                ? "*"
                : origin
        );
    }

    res.setHeader(
        "Access-Control-Allow-Methods",
        "POST, OPTIONS"
    );

    res.setHeader(
        "Access-Control-Allow-Headers",
        "Content-Type"
    );

    res.setHeader(
        "Vary",
        "Origin"
    );


    // ==================================================
    // OPTIONS
    // ==================================================

    if (req.method === "OPTIONS") {
        return res.status(204).end();
    }


    // ==================================================
    // Только POST
    // ==================================================

    if (req.method !== "POST") {
        return res.status(405).json({
            error: "Method not allowed"
        });
    }


    // ==================================================
    // API KEY
    // ==================================================

    const apiKey =
        process.env.OPENROUTER_API_KEY;

    if (!apiKey) {
        return res.status(500).json({
            error:
                "OPENROUTER_API_KEY is not configured"
        });
    }


    try {

        // ==================================================
        // BODY
        // ==================================================

        const body = req.body || {};

        const mode =
            typeof body.mode === "string"
                ? body.mode
                : "general";

        const messages =
            Array.isArray(body.messages)
                ? body.messages
                : [];


        // ==================================================
        // Лимиты
        // ==================================================

        if (messages.length > 30) {
            return res.status(400).json({
                error: "Too many messages"
            });
        }


        // ==================================================
        // БЕЗОПАСНАЯ ОБРАБОТКА СООБЩЕНИЙ
        //
        // Поддерживаем:
        //
        // 1. обычный текст
        // 2. text + image_url
        // ==================================================

        const safeMessages =
            messages
                .filter(message =>
                    message &&
                    typeof message.role === "string"
                )
                .map(message => {

                    const role =
                        message.role === "assistant"
                            ? "assistant"
                            : "user";


                    // --------------------------------------
                    // Обычное текстовое сообщение
                    // --------------------------------------

                    if (
                        typeof message.content === "string"
                    ) {

                        return {
                            role: role,
                            content:
                                message.content.slice(0, 5000)
                        };

                    }


                    // --------------------------------------
                    // Мультимодальное сообщение
                    // --------------------------------------

                    if (
                        Array.isArray(
                            message.content
                        )
                    ) {

                        const safeContent =
                            message.content
                                .filter(part => {

                                    if (
                                        !part ||
                                        typeof part.type !== "string"
                                    ) {
                                        return false;
                                    }


                                    if (
                                        part.type === "text" &&
                                        typeof part.text === "string"
                                    ) {
                                        return true;
                                    }


                                    if (
                                        part.type === "image_url" &&
                                        part.image_url &&
                                        typeof part.image_url.url === "string"
                                    ) {

                                        // Разрешаем только изображения
                                        return (
                                            part.image_url.url.startsWith(
                                                "data:image/"
                                            ) ||
                                            part.image_url.url.startsWith(
                                                "http://"
                                            ) ||
                                            part.image_url.url.startsWith(
                                                "https://"
                                            )
                                        );

                                    }


                                    return false;

                                })
                                .map(part => {

                                    if (
                                        part.type === "text"
                                    ) {

                                        return {
                                            type: "text",
                                            text:
                                                part.text.slice(
                                                    0,
                                                    5000
                                                )
                                        };

                                    }


                                    return {
                                        type: "image_url",
                                        image_url: {
                                            url:
                                                part.image_url.url.slice(
                                                    0,
                                                    2200000
                                                )
                                        }
                                    };

                                });


                        return {
                            role: role,
                            content: safeContent
                        };

                    }


                    return {
                        role: role,
                        content: ""
                    };

                })
                .slice(-30);


        // ==================================================
        // SYSTEM PROMPTS
        // ==================================================

        const prompts = {


            // ==============================================
            // ОБЩИЙ
            // ==============================================

            general: `
Ты универсальный AI-помощник на персональном рабочем портале риелтора.

Отвечай на русском языке, если пользователь не просит другой язык.

Отвечай понятно, естественно и по делу.

Используй предыдущий контекст диалога.

Не выдумывай факты.

Если данных недостаточно — задай уточняющий вопрос.

Не используй длинные вступления.

Делай ответы удобными для чтения в веб-чате.
            `.trim(),


            // ==============================================
            // ОБЪЕКТ
            // ==============================================

            property: `
Ты специализированный AI-помощник риелтора по недвижимости.

Помогай:

- анализировать объекты;
- составлять характеристики;
- находить преимущества;
- формировать продающие описания;
- придумывать заголовки;
- структурировать информацию;
- анализировать сильные и слабые стороны;
- подготавливать текст для клиента.

Не выдумывай характеристики, которых нет в исходных данных.

Если данных недостаточно — попроси необходимые параметры.

Отвечай профессионально, но простым человеческим языком.
            `.trim(),


            // ==============================================
            // TELEGRAM
            // ==============================================

            telegram: `
Ты AI-помощник риелтора, специализирующийся на Telegram.

Создавай привлекательные, но честные тексты.

Используй:

- сильный заголовок;
- короткие абзацы;
- конкретные преимущества;
- умеренное количество эмодзи;
- понятный призыв к действию.

Не используй чрезмерно рекламный стиль.

Не выдумывай цену, площадь, характеристики или преимущества.

Форматируй текст так, чтобы его можно было сразу публиковать в Telegram.
            `.trim(),


            // ==============================================
            // КЛИЕНТ
            // ==============================================

            client: `
Ты AI-помощник риелтора по работе с клиентами.

Помогай составлять естественные ответы клиентам.

Твои задачи:

- отвечать вежливо;
- снимать возражения;
- помогать вести диалог;
- объяснять преимущества объекта;
- предлагать следующий шаг;
- помогать доводить диалог до встречи или просмотра.

Не дави на клиента.

Не используй канцелярит.

Пиши естественно, как хороший современный специалист по недвижимости.

Когда пользователь присылает сообщение клиента,
сначала предложи готовый ответ, который можно сразу отправить.
            `.trim(),


            // ==============================================
            // СРАВНЕНИЕ
            // ==============================================

            comparison: `
Ты AI-помощник риелтора, специализирующийся на сравнении объектов недвижимости.

Сравнивай:

- цену;
- площадь;
- цену за м²;
- количество комнат;
- этаж;
- расположение;
- срок сдачи;
- отделку;
- инфраструктуру;
- преимущества;
- недостатки.

Не придумывай отсутствующие данные.

В конце делай краткий вывод.

Используй формат:

Лучше выбрать объект A, если...

Лучше выбрать объект B, если...
            `.trim(),


            // ==============================================
            // ИПОТЕКА
            // ==============================================

            mortgage: `
Ты AI-помощник риелтора по ипотечным расчётам.

Помогай анализировать:

- стоимость квартиры;
- первоначальный взнос;
- сумму кредита;
- процентную ставку;
- срок;
- ежемесячный платёж;
- общую сумму выплат;
- переплату.

Отделяй приблизительный расчёт от официальных банковских условий.

Не утверждай, что расчёт является банковским предложением.

Если данных недостаточно — попроси их.
            `.trim(),


            // ==============================================
            // ФОТО
            // ==============================================

            photo: `
Ты AI-помощник риелтора, специализирующийся на анализе фотографий недвижимости.

Внимательно анализируй переданное изображение.

Определи, что можно достоверно увидеть:

- помещение;
- мебель;
- отделку;
- освещение;
- состояние;
- видимые особенности;
- преимущества;
- возможные недостатки.

Не утверждай то, чего нельзя достоверно определить по фотографии.

Если изображение позволяет подготовить продающее описание —
предложи такой вариант.

Если пользователь задаёт конкретный вопрос по фотографии,
ответь именно на него.
            `.trim(),


            // ==============================================
            // ПЛАНИРОВКА
            // ==============================================

            floorplan: `
Ты AI-помощник риелтора, специализирующийся на анализе планировок.

Внимательно анализируй переданную планировку.

Определи, насколько возможно:

- количество помещений;
- расположение комнат;
- кухню;
- санузлы;
- прихожую;
- наличие балкона или лоджии;
- кухню-гостиную;
- проходные помещения;
- возможные сильные стороны;
- возможные недостатки;
- особенности зонирования.

Если на изображении указаны площади —
используй именно их.

Не придумывай размеры, которых невозможно определить.

Не выдавай приблизительные визуальные оценки за точные строительные размеры.

Если пользователь просит сделать продающее описание планировки —
сформируй его понятным языком.
            `.trim()

        };


        // ==================================================
        // SYSTEM PROMPT
        // ==================================================

        const systemPrompt =
            prompts[mode] ||
            prompts.general;


        // ==================================================
        // OPENROUTER
        // ==================================================

        const openRouterResponse =
            await fetch(
                "https://openrouter.ai/api/v1/chat/completions",
                {

                    method: "POST",

                    headers: {

                        "Authorization":
                            `Bearer ${apiKey}`,

                        "Content-Type":
                            "application/json",

                        "HTTP-Referer":
                            process.env.TILDA_ORIGIN ||
                            "https://example.com",

                        "X-Title":
                            "Tilda AI Assistant"

                    },

                    body: JSON.stringify({

                        model:
                            "openrouter/free",

                        messages: [

                            {
                                role: "system",
                                content:
                                    systemPrompt
                            },

                            ...safeMessages

                        ],

                        temperature:
                            0.7,

                        max_tokens:
                            1400

                    })

                }
            );


        // ==================================================
        // OPENROUTER RESPONSE
        // ==================================================

        const data =
            await openRouterResponse.json();


        if (!openRouterResponse.ok) {

            console.error(
                "OpenRouter error:",
                data
            );

            return res
                .status(openRouterResponse.status)
                .json({

                    error:
                        data?.error?.message ||
                        "OpenRouter error"

                });

        }


        // ==================================================
        // ANSWER
        // ==================================================

        const answer =
            data?.choices?.[0]?.message?.content;


        if (!answer) {

            return res.status(500).json({

                error:
                    "AI returned empty response"

            });

        }


        return res.status(200).json({

            answer: answer

        });


    } catch (error) {

        console.error(
            "Server error:",
            error
        );


        return res.status(500).json({

            error:
                error?.message ||
                "Internal server error"

        });

    }

}
