export default async function handler(req, res) {

    // ==================================================
    // CORS
    // ==================================================

    const origin = req.headers.origin;

    const allowedOrigin =
        process.env.TILDA_ORIGIN || "*";

    if (
        allowedOrigin === "*" ||
        origin === allowedOrigin
    ) {
        res.setHeader(
            "Access-Control-Allow-Origin",
            allowedOrigin === "*"
                ? "*"
                : origin
        );
    }

    res.setHeader(
        "Access-Control-Allow-Methods",
        "POST, OPTIONS"
    );

    res.setHeader(
        "Access-Control-Allow-Headers",
        "Content-Type"
    );

    res.setHeader(
        "Vary",
        "Origin"
    );


    // ==================================================
    // OPTIONS
    // ==================================================

    if (req.method === "OPTIONS") {

        return res.status(204).end();

    }


    // ==================================================
    // Только POST
    // ==================================================

    if (req.method !== "POST") {

        return res.status(405).json({
            error: "Method not allowed"
        });

    }


    // ==================================================
    // API KEY
    // ==================================================

    const apiKey =
        process.env.OPENROUTER_API_KEY;


    if (!apiKey) {

        return res.status(500).json({
            error:
                "OPENROUTER_API_KEY is not configured"
        });

    }


    try {

        // ==================================================
        // Получаем данные
        // ==================================================

        const body = req.body || {};

        const mode =
            typeof body.mode === "string"
                ? body.mode
                : "general";

        const messages =
            Array.isArray(body.messages)
                ? body.messages
                : [];


        // ==================================================
        // Максимальная история
        // ==================================================

        if (messages.length > 30) {

            return res.status(400).json({
                error: "Too many messages"
            });

        }


        // ==================================================
        // Защита входных данных
        // ==================================================

        const safeMessages =
            messages
                .filter(message =>
                    message &&
                    typeof message.role === "string" &&
                    typeof message.content === "string"
                )
                .map(message => ({

                    role:
                        message.role === "assistant"
                            ? "assistant"
                            : "user",

                    content:
                        message.content.slice(0, 5000)

                }))
                .slice(-30);


        // ==================================================
        // SYSTEM PROMPTS
        // ==================================================

        const prompts = {


            // ------------------------------------------------
            // ОБЩИЙ
            // ------------------------------------------------

            general: `
Ты универсальный AI-помощник на персональном портале.

Отвечай на русском языке, если пользователь не просит другой язык.

Отвечай понятно, естественно и по делу.

Используй контекст предыдущих сообщений.

Не выдумывай факты.

Если информации недостаточно, задай уточняющий вопрос.

Не используй длинные вступления.

Форматируй ответы так, чтобы их было удобно читать в чате.
            `.trim(),


            // ------------------------------------------------
            // ОБЪЕКТ
            // ------------------------------------------------

            property: `
Ты специализированный AI-помощник риелтора.

Твоя задача — помогать работать с объектами недвижимости.

Помогай:

- анализировать квартиру;
- составлять характеристики;
- находить преимущества объекта;
- формировать продающие описания;
- придумывать заголовки;
- структурировать информацию;
- выявлять сильные и слабые стороны объекта;
- подготавливать информацию для клиентов.

Не выдумывай характеристики объекта, которых пользователь не указал.

Если данных недостаточно — попроси необходимые параметры.

Пиши профессионально, но простым человеческим языком.

Отвечай на русском языке.
            `.trim(),


            // ------------------------------------------------
            // TELEGRAM
            // ------------------------------------------------

            telegram: `
Ты AI-помощник риелтора, специализирующийся на подготовке публикаций для Telegram.

Создавай привлекательные, но честные тексты.

Используй:

- короткие абзацы;
- понятные преимущества;
- умеренное количество эмодзи;
- сильный заголовок;
- понятный призыв к действию.

Не используй чрезмерно рекламный стиль.

Не выдумывай характеристики, цены, сроки или преимущества.

Если информации недостаточно, сначала задай уточняющий вопрос.

По умолчанию текст должен быть удобен для публикации в Telegram.
            `.trim(),


            // ------------------------------------------------
            // КЛИЕНТ
            // ------------------------------------------------

            client: `
Ты помощник риелтора по работе с клиентами.

Помогай создавать естественные ответы клиентам.

Твоя задача:

- отвечать вежливо;
- снимать возражения;
- помогать вести диалог;
- объяснять преимущества объектов;
- формулировать следующие шаги;
- помогать доводить диалог до встречи или просмотра.

Не дави на клиента.

Не используй канцелярит.

Пиши так, как написал бы хороший современный менеджер по недвижимости.

Если пользователь просит ответить клиенту, сначала дай готовый текст, который можно сразу отправить.
            `.trim(),


            // ------------------------------------------------
            // СРАВНЕНИЕ
            // ------------------------------------------------

            comparison: `
Ты AI-помощник риелтора, специализирующийся на сравнении объектов недвижимости.

Сравнивай объекты по:

- цене;
- площади;
- цене за м²;
- этажу;
- комнатам;
- расположению;
- сроку сдачи;
- отделке;
- инфраструктуре;
- преимуществам;
- недостаткам.

Не придумывай отсутствующие данные.

Используй понятную структуру.

В конце обязательно делай краткий вывод:

"Лучше выбрать объект A, если..."
"Лучше выбрать объект B, если..."

Если информации недостаточно — запроси необходимые параметры.
            `.trim(),


            // ------------------------------------------------
            // ИПОТЕКА
            // ------------------------------------------------

            mortgage: `
Ты помощник риелтора по ипотечным расчетам.

Помогай рассчитывать:

- размер кредита;
- первоначальный взнос;
- ежемесячный платеж;
- общую сумму выплат;
- переплату;
- сравнение нескольких вариантов.

Всегда внимательно проверяй исходные данные.

Если пользователь не указал процентную ставку, срок или другие необходимые параметры — попроси их.

Разделяй приблизительный расчет и точные данные банка.

Не утверждай, что расчет является официальным предложением банка.

Отвечай на русском языке.
            `.trim()

        };


        // ==================================================
        // Определяем prompt
        // ==================================================

        const systemPrompt =
            prompts[mode] ||
            prompts.general;


        // ==================================================
        // Запрос OpenRouter
        // ==================================================

        const openRouterResponse =
            await fetch(
                "https://openrouter.ai/api/v1/chat/completions",
                {

                    method: "POST",

                    headers: {

                        "Authorization":
                            `Bearer ${apiKey}`,

                        "Content-Type":
                            "application/json",

                        "HTTP-Referer":
                            process.env.TILDA_ORIGIN ||
                            "https://example.com",

                        "X-Title":
                            "Tilda AI Assistant"

                    },

                    body: JSON.stringify({

                        model:
                            "openrouter/free",

                        messages: [

                            {
                                role: "system",
                                content: systemPrompt
                            },

                            ...safeMessages

                        ],

                        temperature: 0.7,

                        max_tokens: 1200

                    })

                }
            );


        // ==================================================
        // Ответ OpenRouter
        // ==================================================

        const data =
            await openRouterResponse.json();


        // ==================================================
        // Обработка ошибки
        // ==================================================

        if (!openRouterResponse.ok) {

            console.error(
                "OpenRouter error:",
                data
            );

            return res
                .status(openRouterResponse.status)
                .json({

                    error:
                        data?.error?.message ||
                        "OpenRouter error"

                });

        }


        // ==================================================
        // Получаем ответ
        // ==================================================

        const answer =
            data?.choices?.[0]?.message?.content;


        if (!answer) {

            return res.status(500).json({

                error:
                    "AI returned empty response"

            });

        }


        // ==================================================
        // Отправляем ответ в Tilda
        // ==================================================

        return res.status(200).json({

            answer: answer

        });


    } catch (error) {

        console.error(
            "Server error:",
            error
        );


        return res.status(500).json({

            error:
                error?.message ||
                "Internal server error"

        });

    }

}
