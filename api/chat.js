export default async function handler(req, res) {

    // ==================================================
    // CORS
    // ==================================================

    const origin = req.headers.origin;

    const allowedOrigin =
        process.env.TILDA_ORIGIN || "*";

    if (
        allowedOrigin === "*" ||
        origin === allowedOrigin
    ) {
        res.setHeader(
            "Access-Control-Allow-Origin",
            allowedOrigin === "*"
                ? "*"
                : origin
        );
    }

    res.setHeader(
        "Access-Control-Allow-Methods",
        "POST, OPTIONS"
    );

    res.setHeader(
        "Access-Control-Allow-Headers",
        "Content-Type"
    );

    res.setHeader(
        "Vary",
        "Origin"
    );


    // ==================================================
    // OPTIONS
    // ==================================================

    if (req.method === "OPTIONS") {
        return res.status(204).end();
    }


    // ==================================================
    // POST
    // ==================================================

    if (req.method !== "POST") {
        return res.status(405).json({
            error: "Method not allowed"
        });
    }


    // ==================================================
    // API KEY
    // ==================================================

    const apiKey =
        process.env.OPENROUTER_API_KEY;

    if (!apiKey) {
        return res.status(500).json({
            error:
                "OPENROUTER_API_KEY is not configured"
        });
    }


    try {

        // ==================================================
        // BODY
        // ==================================================

        const body =
            req.body || {};

        const mode =
            typeof body.mode === "string"
                ? body.mode
                : "general";

        const tone =
            typeof body.tone === "string"
                ? body.tone
                : "default";

        const messages =
            Array.isArray(body.messages)
                ? body.messages
                : [];

        const pageContext =
            typeof body.pageContext === "string"
                ? body.pageContext.slice(0, 12000)
                : "";


        // ==================================================
        // LIMITS
        // ==================================================

        if (messages.length > 30) {
            return res.status(400).json({
                error:
                    "Слишком большая история чата. Начните новую переписку."
            });
        }


        // ==================================================
        // SAFE MESSAGES
        // ==================================================

        const safeMessages =
            messages
                .filter(message =>
                    message &&
                    typeof message.role === "string"
                )
                .map(message => {

                    const role =
                        message.role === "assistant"
                            ? "assistant"
                            : "user";


                    // --------------------------------------
                    // TEXT
                    // --------------------------------------

                    if (
                        typeof message.content === "string"
                    ) {

                        return {
                            role,
                            content:
                                message.content.slice(0, 5000)
                        };

                    }


                    // --------------------------------------
                    // MULTIMODAL
                    // --------------------------------------

                    if (
                        Array.isArray(message.content)
                    ) {

                        const safeContent =
                            message.content
                                .filter(part => {

                                    if (
                                        !part ||
                                        typeof part.type !== "string"
                                    ) {
                                        return false;
                                    }


                                    if (
                                        part.type === "text" &&
                                        typeof part.text === "string"
                                    ) {
                                        return true;
                                    }


                                    if (
                                        part.type === "image_url" &&
                                        part.image_url &&
                                        typeof part.image_url.url === "string"
                                    ) {

                                        return (
                                            part.image_url.url.startsWith(
                                                "data:image/"
                                            ) ||
                                            part.image_url.url.startsWith(
                                                "http://"
                                            ) ||
                                            part.image_url.url.startsWith(
                                                "https://"
                                            )
                                        );

                                    }

                                    return false;

                                })
                                .map(part => {

                                    if (
                                        part.type === "text"
                                    ) {

                                        return {
                                            type: "text",
                                            text:
                                                part.text.slice(
                                                    0,
                                                    5000
                                                )
                                        };

                                    }


                                    return {
                                        type: "image_url",
                                        image_url: {
                                            url:
                                                part.image_url.url.slice(
                                                    0,
                                                    2200000
                                                )
                                        }
                                    };

                                });


                        return {
                            role,
                            content:
                                safeContent
                        };

                    }


                    return {
                        role,
                        content: ""
                    };

                })
                .slice(-30);


        // ==================================================
        // TONE
        // ==================================================

        const toneInstructions = {

            default:
                "",

            business:
                "Стиль ответа: деловой, профессиональный и структурированный.",

            friendly:
                "Стиль ответа: дружелюбный, естественный и лёгкий для восприятия.",

            selling:
                "Стиль ответа: более продающий и убедительный, но без агрессивного давления и без выдумывания преимуществ.",

            premium:
                "Стиль ответа: сдержанный, дорогой и премиальный. Избегай дешёвых рекламных формулировок.",

            simple:
                "Стиль ответа: максимально простой и понятный человеческий язык без профессионального жаргона."

        };


        const tonePrompt =
            toneInstructions[tone] ||
            toneInstructions.default;


        // ==================================================
        // BASE PROMPTS
        // ==================================================

        const prompts = {


            general: `
Ты универсальный AI-помощник на персональном рабочем портале риелтора.

Отвечай на русском языке, если пользователь не просит другой язык.

Отвечай понятно, естественно и по делу.

Используй контекст предыдущих сообщений.

Если для выполнения задачи не хватает важных данных,
не выдумывай их.

Вместо этого задай не более 3 конкретных уточняющих вопросов.

Не повторяй без необходимости уже известную информацию.

Делай ответы удобными для чтения в веб-чате.

Не пиши длинные вступления.
            `.trim(),


            property: `
Ты специализированный AI-помощник риелтора по объектам недвижимости.

Помогай:

- анализировать объект;
- находить преимущества;
- находить слабые стороны;
- составлять характеристики;
- писать продающие описания;
- придумывать заголовки;
- структурировать данные объекта;
- объяснять объект клиенту.

Не выдумывай характеристики.

Если важных данных не хватает,
задай не более 3 уточняющих вопросов.

Используй данные текущей страницы,
если они переданы в контексте.

Отвечай профессионально, но простым языком.
            `.trim(),


            telegram: `
Ты AI-помощник риелтора, специализирующийся на Telegram.

Создавай готовые к публикации посты.

Используй:

- сильный заголовок;
- короткие абзацы;
- конкретные преимущества;
- умеренное количество эмодзи;
- понятный призыв к действию.

Не выдумывай характеристики объекта.

Если критически важной информации недостаточно,
сначала задай не более 3 уточняющих вопросов.

Не используй навязчивый или дешёвый рекламный стиль.
            `.trim(),


            client: `
Ты AI-помощник риелтора по работе с клиентами.

Помогай составлять естественные сообщения клиентам.

Твоя задача:

- отвечать вежливо;
- снимать возражения;
- объяснять преимущества;
- вести клиента к следующему действию;
- помогать подготовить ответ после звонка или просмотра;
- делать сообщения естественными.

Не дави на клиента.

Не используй канцелярит.

Когда пользователь присылает сообщение клиента,
дай готовый вариант ответа.

При нехватке важного контекста сначала задай уточняющие вопросы.
            `.trim(),


            comparison: `
Ты AI-помощник риелтора, специализирующийся на сравнении недвижимости.

Сравнивай:

- цену;
- площадь;
- цену за м²;
- количество комнат;
- этаж;
- расположение;
- срок сдачи;
- отделку;
- инфраструктуру;
- преимущества;
- недостатки.

Не выдумывай данные.

Используй только предоставленную информацию.

В конце дай практический вывод:
какой объект лучше для какого типа покупателя.
            `.trim(),


            mortgage: `
Ты AI-помощник риелтора по ипотечным расчётам.

Помогай объяснять:

- сумму кредита;
- первоначальный взнос;
- ежемесячный платёж;
- общую выплату;
- переплату;
- влияние ставки и срока.

Не выдавай расчёт за официальное банковское предложение.

Если данных недостаточно,
задай необходимые вопросы.
            `.trim(),


            photo: `
Ты AI-помощник риелтора, специализирующийся на анализе фотографий недвижимости.

Определи только то, что можно достоверно увидеть.

Анализируй:

- помещение;
- отделку;
- мебель;
- состояние;
- освещение;
- видимые особенности;
- достоинства;
- возможные недостатки.

Не выдумывай скрытые характеристики.

Не делай вид, что знаешь то,
чего нельзя определить по изображению.
            `.trim(),


            floorplan: `
Ты AI-помощник риелтора, специализирующийся на анализе планировок.

Анализируй изображение планировки.

Определи, насколько возможно:

- количество помещений;
- назначение помещений;
- расположение комнат;
- кухню;
- санузлы;
- прихожую;
- балкон или лоджию;
- кухню-гостиную;
- проходные помещения;
- сильные и слабые стороны планировки.

Если на плане указаны площади,
используй именно их.

Не выдавай визуальные оценки размеров за точные размеры.
            `.trim()

        };


        // ==================================================
        // OBJECT CONTEXT
        // ==================================================

        let contextMessage = "";


        if (pageContext) {

            contextMessage = `

КОНТЕКСТ ТЕКУЩЕЙ СТРАНИЦЫ:

${pageContext}

Используй этот контекст как дополнительную информацию
об объекте или странице.

Не придумывай значения, которых в нём нет.
            `.trim();

        }


        // ==================================================
        // SYSTEM PROMPT
        // ==================================================

        const systemPrompt = [

            prompts[mode] ||
            prompts.general,

            tonePrompt,

            contextMessage

        ]
            .filter(Boolean)
            .join("\n\n");


        // ==================================================
        // OPENROUTER
        // ==================================================

        const openRouterResponse =
            await fetch(
                "https://openrouter.ai/api/v1/chat/completions",
                {

                    method:
                        "POST",

                    headers: {

                        "Authorization":
                            `Bearer ${apiKey}`,

                        "Content-Type":
                            "application/json",

                        "HTTP-Referer":
                            process.env.TILDA_ORIGIN ||
                            "https://example.com",

                        "X-Title":
                            "Tilda AI Assistant"

                    },

                    body:
                        JSON.stringify({

                            model:
                                "openrouter/free",

                            messages: [

                                {
                                    role:
                                        "system",

                                    content:
                                        systemPrompt
                                },

                                ...safeMessages

                            ],

                            temperature:
                                0.7,

                            max_tokens:
                                1400

                        })

                }
            );


        // ==================================================
        // OPENROUTER RESPONSE
        // ==================================================

        const data =
            await openRouterResponse.json();


        if (!openRouterResponse.ok) {

            console.error(
                "OpenRouter error:",
                data
            );

            return res
                .status(
                    openRouterResponse.status
                )
                .json({

                    error:
                        data?.error?.message ||
                        "Ошибка OpenRouter"

                });

        }


        // ==================================================
        // ANSWER
        // ==================================================

        const answer =
            data?.choices?.[0]?.message?.content;


        if (!answer) {

            return res.status(500).json({

                error:
                    "AI не вернул ответ"

            });

        }


        // ==================================================
        // RESULT
        // ==================================================

        return res.status(200).json({

            answer:
                answer

        });


    } catch (error) {

        console.error(
            "Server error:",
            error
        );


        return res.status(500).json({

            error:
                error?.message ||
                "Внутренняя ошибка сервера"

        });

    }

}
